#!/usr/bin/env python3
"""
评分系统 — Scoring System
提交代码质量评分，百分制，≥90 分达标。

评分维度:
  - 功能正确性 (40分) — pytest 通过率
  - 安全性     (35分) — 作弊检测+静态分析
  - 代码质量   (15分) — pylint + 圈复杂度
  - 性能       (10分) — 执行效率

一票否决项（0分）:
  - AST 检测到直接返回预期输出
  - 删除/篡改测试用例
  - 引入外部恶意依赖
  - 代码为空/乱码
  - bandit 检测到高危漏洞
  - 检测到自动提交机器人特征
  - 检测到重复提交/批量提交行为

用法:
    python scripts/score.py --code <file> --tests <test_dir>
    python scripts/score.py --check <file>   # 仅检查作弊
"""

