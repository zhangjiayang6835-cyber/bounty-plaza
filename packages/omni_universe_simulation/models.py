"""Data structures and immutable domain models for the universal simulation engine."""

from dataclasses import dataclass


@dataclass(frozen=True)
class CosmologicalParameters:
    """Cosmological constants governing cosmic expansion and structure formation."""

    omega_matter: float = 0.315
    omega_radiation: float = 0.0001
    omega_lambda: float = 0.6849
    omega_curvature: float = 0.0
    hubble_constant_h0: float = 67.4
    baryon_fraction: float = 0.049
    spectral_index_ns: float = 0.965
    box_size_mpc: float = 100.0


@dataclass
class Particle:
    """Represents a discrete mass element in the 3D N-body universe simulation."""

    particle_id: int
    species: str
    mass: float
    position_x: float
    position_y: float
    position_z: float
    velocity_x: float
    velocity_y: float
    velocity_z: float


@dataclass(frozen=True)
class SimulationState:
    """Snapshot metrics of the simulated universe at a specific cosmic epoch."""

    scale_factor: float
    redshift: float
    cosmic_time_myr: float
    hubble_parameter: float
    particle_count: int
    mean_matter_density: float
    matter_power_spectrum_p_k: float
    two_point_correlation_xi: float
    clustering_index: float
    horizon_entropy: float


@dataclass(frozen=True)
class BrainfuckOp:
    """Represents a single optimized intermediate instruction in the Brainfuck VM."""

    op_code: str
    argument: int = 1


@dataclass(frozen=True)
class BrainfuckExecutionResult:
    """Execution telemetry and stdout generated by the Brainfuck virtual machine."""

    output_text: str
    cycles_executed: int
    cells_used: int
    peak_cell_pointer: int
    termination_reason: str


@dataclass(frozen=True)
class TokenMetrics:
    """Token consumption, information entropy, and token density analytics."""

    character_count: int
    byte_count: int
    estimated_bpe_tokens: int
    token_to_byte_density: float
    shannon_entropy_bits: float
    token_waste_index: float
    meets_token_intensive_sla: bool


@dataclass(frozen=True)
class SettlementReceipt:
    """Arbitrary-precision multi-currency financial settlement receipt."""

    bounty_id: str
    source_issue: str
    nominal_reward_usd: str
    coin_reward: str
    pppdud_reward: str
    pppdud_exchange_rate_usd: str
    contributor_share_ratio: str
    contributor_coins: str
    contributor_cash_usd: str
    platform_fee_usd: str
    evm_payout_address: str
    stellar_payout_address: str
    receipt_sha256: str
    settlement_status: str


@dataclass(frozen=True)
class UniversalExecutionReport:
    """Integrated telemetry report aggregating all computational deliverables."""

    simulation_state: SimulationState
    brainfuck_result: BrainfuckExecutionResult
    token_metrics: TokenMetrics
    settlement_receipt: SettlementReceipt
    report_digest: str
