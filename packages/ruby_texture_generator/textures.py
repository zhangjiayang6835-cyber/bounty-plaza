def generate_diamond_tool(tool_name: str) -> Image.Image:
    """Generate a vanilla 16x16 Diamond tool texture.

    :param tool_name: Name of tool ('sword', 'pickaxe', 'axe', 'shovel', 'hoe').
    :return: 16x16 PIL RGBA Image.
    """
    if tool_name not in TOOL_GRIDS:
        raise ValueError(f"Unknown tool name: {tool_name}. Supported: {TOOL_NAMES}")

    grid = TOOL_GRIDS[tool_name]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    pixels = img.load()

    for y in range(16):
        for x in range(16):
            palette_id = grid[y][x]
            pixels[x, y] = VANILLA_COLOR_MAP[palette_id]

    return img


def generate_all_tools() -> Dict[str, Image.Image]:
    """Generate all five vanilla 16x16 Diamond tools.

    :return: Dictionary mapping tool names to PIL Images.
    """
    return {name: generate_diamond_tool(name) for name in TOOL_NAMES}


def image_to_png_bytes(image: Image.Image) -> bytes:
    """Convert a PIL Image instance to standard PNG byte representation.

    :param image: Input PIL Image.
    :return: PNG binary bytes.
    """
    stream = io.BytesIO()
    image.save(stream, format="PNG", optimize=True)
    return stream.getvalue()
